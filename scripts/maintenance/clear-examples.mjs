import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const appRoot=fileURLToPath(new URL('../../',import.meta.url));
const base='http://127.0.0.1:4317';
const health=await (await fetch(`${base}/api/health`)).json();
if(health.app!=='local-learning-notes'||path.resolve(health.root)!==appRoot)throw new Error('Current service is not this app.');
const seedPath=path.join(appRoot,'data','seed.json');
const seed=JSON.parse(await fs.readFile(seedPath,'utf8'));
const current=await (await fetch(`${base}/api/notebook`)).json();
const exampleIds=new Set(seed.notes.filter(n=>n.content.includes('示例')).map(n=>n.id));
const toRemove=current.notes.filter(n=>exampleIds.has(n.id)&&n.content.includes('示例'));
const ids=new Set(toRemove.map(n=>n.id));
const archiveDir=path.join(appRoot,'data','archives');
await fs.mkdir(archiveDir,{recursive:true});
const backup=path.join(archiveDir,`before-example-clear-${new Date().toISOString().replace(/[:.]/g,'-')}.json`);
await fs.writeFile(backup,JSON.stringify(current,null,2)+'\n',{encoding:'utf8',flag:'wx'});
const cleaned={...current,topics:current.topics.map(t=>({...t,description:(t.description||'').replace(/^示例主题[：:]\s*/, '')})),notes:current.notes.filter(n=>!ids.has(n.id)),links:current.links.filter(l=>!ids.has(l.from)&&!ids.has(l.to))};
const response=await fetch(`${base}/api/notebook`,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({notebook:cleaned,baseRevision:current.revision})});
const saved=await response.json();
if(!response.ok)throw new Error(saved.message||'Clear failed, current notebook was not overwritten.');
await fs.writeFile(seedPath,JSON.stringify({version:1,revision:0,topics:cleaned.topics,notes:[],links:[]},null,2)+'\n','utf8');
console.log(JSON.stringify({removed:toRemove.length,remaining:saved.notes.length,links:saved.links.length,topics:saved.topics.length,backup},null,2));
